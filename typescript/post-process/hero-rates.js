// npm run herorates: per-hero win rates of OHA bots against OHA bots, for the `heropick` flag.
//
// Reads the MATCHREC line of every finished game in datasets/runs/*/console.g<n>.log (the main checkout's,
// also when run from a worktree), skipping batches whose name starts with "smoke" and the kept copies
// (.dead.log, .crashed.log, .smoke.log). A log copied into a second folder (a replayed game) counts once:
// games are keyed by their MATCHREC text. Both teams of every game count, plain and new code alike: each
// side is one hero-game per hero, won when its team is the winner.
//
// The rate is shrunk toward 0.5: (wins + 5) / (games + 10), so a hero seen in a handful of games stays near
// even. Writes bots/FunLib/hero_win_rates.lua (a hero missing from it reads as 0.5 in hero_selection.lua)
// and prints the top and bottom 10.
//
//   npm run herorates [-- --runs=<dir>] [--out=<file>]
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const crypto = require("crypto");

const root = path.join(__dirname, "../..");
const mainRoot = (() => {
    const r = spawnSync("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], { cwd: root, encoding: "utf8" });
    const common = (r.stdout || "").trim();
    return r.status === 0 && common ? path.dirname(path.resolve(common)) : root;
})();
const arg = name => {
    const a = process.argv.find(s => s.startsWith(`--${name}=`));
    return a ? a.slice(name.length + 3) : null;
};
const runsDir = path.resolve(arg("runs") || path.join(mainRoot, "datasets/runs"));
const outFile = path.resolve(arg("out") || path.join(root, "bots/FunLib/hero_win_rates.lua"));
const PRIOR_WINS = 5;
const PRIOR_GAMES = 10;

if (!fs.existsSync(runsDir)) {
    console.error(`No runs folder: ${runsDir}`);
    process.exit(1);
}

const seen = new Set();
const stats = {}; // hero -> { n, w }
let games = 0;
let batches = 0;
for (const b of fs.readdirSync(runsDir, { withFileTypes: true })) {
    if (!b.isDirectory() || b.name.startsWith("smoke")) continue;
    const dir = path.join(runsDir, b.name);
    let used = false;
    for (const f of fs.readdirSync(dir)) {
        if (!/^console\.g\d+\.log$/.test(f)) continue;
        const text = fs.readFileSync(path.join(dir, f), "utf8");
        const i = text.indexOf("MATCHREC {");
        if (i < 0) continue;
        const end = text.indexOf("\n", i);
        const json = text.slice(i + 9, end < 0 ? undefined : end).trim();
        // A hash, not the slice: a sliced string keeps the whole log text alive.
        const key = crypto.createHash("sha1").update(json).digest("hex");
        if (seen.has(key)) continue;
        let rec;
        try {
            rec = JSON.parse(json);
        } catch (e) {
            continue; // partial line
        }
        const lineup = rec.lineup || {};
        if (rec.winner !== "radiant" && rec.winner !== "dire") continue;
        if (!Array.isArray(lineup.radiant) || !Array.isArray(lineup.dire)) continue;
        seen.add(key);
        games++;
        used = true;
        for (const side of ["radiant", "dire"]) {
            for (const hero of lineup[side]) {
                if (typeof hero !== "string" || !hero.startsWith("npc_dota_hero_")) continue;
                const s = (stats[hero] = stats[hero] || { n: 0, w: 0 });
                s.n++;
                if (rec.winner === side) s.w++;
            }
        }
    }
    if (used) batches++;
}

if (games === 0) {
    console.error(`No finished games (MATCHREC) under ${runsDir}`);
    process.exit(1);
}

const rows = Object.keys(stats)
    .map(h => ({ hero: h, n: stats[h].n, w: stats[h].w, rate: (stats[h].w + PRIOR_WINS) / (stats[h].n + PRIOR_GAMES) }))
    .sort((a, b) => b.rate - a.rate || b.n - a.n || (a.hero < b.hero ? -1 : 1));

const date = new Date().toISOString().slice(0, 10);
const lines = [
    "-- Generated by `npm run herorates` (typescript/post-process/hero-rates.js). Do not edit by hand.",
    `-- ${date}: ${games} finished games from ${batches} batches in datasets/runs (smoke batches excluded),`,
    "-- both teams of every game counted (plain OHA and flagged code alike), one hero-game per side.",
    `-- Rate = (wins + ${PRIOR_WINS}) / (games + ${PRIOR_GAMES}), shrunk toward 0.5. A hero missing here reads as 0.5.`,
    "-- Read by hero_selection.lua when the `heropick` flag is on for the team.",
    "-- hero = rate, -- wins/games",
    "return {",
];
for (const r of [...rows].sort((a, b) => (a.hero < b.hero ? -1 : 1))) {
    lines.push(`\t${r.hero} = ${r.rate.toFixed(3)}, -- ${r.w}/${r.n}`);
}
lines.push("}");
fs.writeFileSync(outFile, lines.join("\n") + "\n");

const show = r => `  ${r.rate.toFixed(3)}  ${String(r.w).padStart(4)}/${String(r.n).padEnd(4)}  ${r.hero.replace("npc_dota_hero_", "")}`;
console.log(`${games} games (${batches} batches), ${rows.length} heroes -> ${path.relative(process.cwd(), outFile) || outFile}`);
console.log("Top 10:");
for (const r of rows.slice(0, 10)) console.log(show(r));
console.log("Bottom 10:");
for (const r of rows.slice(-10)) console.log(show(r));
